// Inlines the UI files into a TypeScript module.
//
// Why: Wrangler's `rules` cannot turn a .js import into a text module (JS rules
// are ignored while bundling), and Static Assets would suppress ctx.access for
// every request. Generating a module keeps the UI editable as real .html/.css/.js
// files while the Worker bundles them as plain strings.
//
// Run via `npm run build:ui` (also wired to predev / predeploy / pretypecheck).

import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const uiDir = join(here, "..", "src", "ui");

const files = {
  uiHtml: "index.html",
  uiCss: "style.css",
  uiAppJs: "app.js",
  uiViewJs: "view.js",
  uiManageJs: "manage.js",
};

const parts = [
  "// Generated by scripts/gen-ui.mjs — do not edit directly.",
  "// Source of truth: src/ui/{index.html,style.css,app.js,view.js,manage.js}",
  "",
];

const hash = createHash("sha256");

for (const [exportName, fileName] of Object.entries(files)) {
  const content = await readFile(join(uiDir, fileName), "utf8");
  hash.update(fileName);
  hash.update(content);
  parts.push(`export const ${exportName} = ${JSON.stringify(content)};`);
  parts.push("");
}

const version = hash.digest("hex").slice(0, 10);
parts.push(`export const uiVersion = ${JSON.stringify(version)};`);
parts.push("");

const fontPath = join(uiDir, "fonts", "space-grotesk-700.woff2");
const font = await readFile(fontPath);
parts.push(`export const displayFont = ${JSON.stringify(font.toString("base64"))};`);
parts.push("");

await writeFile(join(uiDir, "generated.ts"), parts.join("\n"), "utf8");
console.log(`gen-ui: wrote src/ui/generated.ts (${Object.keys(files).length} files)`);
